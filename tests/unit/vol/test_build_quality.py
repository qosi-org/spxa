"""Quality reports of built surfaces."""

from __future__ import annotations

import dataclasses

import numpy as np
import pytest

from spxa.vol.build import build_vol_surface
from spxa.vol.bumps import expiry_buckets
from tests.unit.vol.test_build import QUOTES

BUILD = build_vol_surface(QUOTES, "ssvi")


def test_clean_build_report() -> None:
    q = BUILD.quality()
    assert q.arbitrage_free and q.calendar_free and q.worst_calendar <= 0
    assert len(q.expiries) == 5
    assert q.worst_vol_error < 1e-6  # data generated by SSVI
    e = q.expiries[3]
    assert e.expiry == 1.0 and e.n_quotes == BUILD.ks[3].size and e.min_g > 0
    assert e.vol_rmse == pytest.approx(BUILD.vol_rmse[3], abs=1e-15)
    assert e.atm_skew < 0
    text = q.table()
    assert text.count("\n") == 6 and text.endswith("calendar-free")


def test_report_flags_calendar_and_butterfly_arbitrage() -> None:
    T = list(BUILD.expiries)
    sunk = BUILD.surface.bumped(expiry_buckets(T, -0.08)[3])  # 1Y vols 8 points too low
    q = dataclasses.replace(BUILD, surface=sunk).quality()
    assert not q.calendar_free and q.worst_calendar > 1e-3 and not q.arbitrage_free
    assert q.worst_vol_error == pytest.approx(0.08, abs=1e-6)
    assert "calendar arbitrage" in q.table()

    def wiggle(k: np.ndarray, t: float) -> np.ndarray:
        return 0.02 * np.sin(40 * np.asarray(k)) * (abs(t - 0.5) < 1e-12)

    q2 = dataclasses.replace(BUILD, surface=BUILD.surface.bumped(wiggle)).quality()
    flags = [e.butterfly_free for e in q2.expiries]
    assert flags == [True, True, False, True, True] and q2.expiries[2].min_g < 0
    assert "NO" in q2.table()
